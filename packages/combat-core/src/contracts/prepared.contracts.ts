import { z } from 'zod'
import {
  attackTypeSchema,
  burrowConfigSchema,
  statusEffectSchema,
  supportAuraModifierSchema,
  unitSizeSchema,
} from './unit-primitives.contracts.js'

export const preparedStatsSchema = z.object({
  hp: z.number().finite().positive().optional(),
  attack: z.number().finite().nonnegative().optional(),
  defense: z.number().finite().optional(),
  speed: z.number().finite().nonnegative().optional(),
  range: z.number().finite().nonnegative().optional(),
  shield: z.number().finite().nonnegative().optional(),
  actionCooldownMax: z.number().int().positive().optional(),
  turnSpeed: z.number().finite().nonnegative().optional(),
  size: unitSizeSchema.optional(),
  combatTags: z.array(z.string()).optional(),
  attackType: attackTypeSchema.optional(),
  aoeRadius: z.number().finite().nonnegative().optional(),
  minimumRange: z.number().finite().nonnegative().optional(),
  isFlying: z.boolean().optional(),
  canTargetAir: z.boolean().optional(),
  selfDestructOnAttack: z.boolean().optional(),
  stationaryAlignment: z.boolean().optional(),
  formationAnchorMode: z.enum(['leader', 'centroid']).optional(),
  velocityDamping: z.boolean().optional(),
  projectileInterceptable: z.boolean().optional(),
  shieldDamageMult: z.number().finite().optional(),
  armorPierceRatio: z.number().finite().optional(),
  antiAirDamageMult: z.number().finite().optional(),
  summonCounterDamageMult: z.number().finite().optional(),
  accuracyPenaltyResist: z.number().finite().optional(),
  groundDamageMult: z.number().finite().optional(),
  lifestealMult: z.number().finite().optional(),
  executeThreshold: z.number().finite().optional(),
  multishot: z.number().int().positive().optional(),
  movingReduction: z.number().finite().optional(),
  statusOnHit: z.array(statusEffectSchema).optional(),
  healTargetTags: z.array(z.string()).optional(),
  targetingProfile: z.string().optional(),
  spawnType: z.string().optional(),
  spawnCap: z.number().int().positive().optional(),
  appliesEmp: z.boolean().optional(),
  leavesPuddle: z.boolean().optional(),
  replicateOnKill: z.boolean().optional(),
  resurrectOnce: z.boolean().optional(),
  stealthUntilAttack: z.boolean().optional(),
  onDeathPuddle: z.enum(['napalm', 'acid', 'emp']).optional(),
  spawnerConfig: z.object({ unitType: z.string(), interval: z.number(), timer: z.number().optional() }).optional(),
  burrowConfig: burrowConfigSchema.optional(),
  supportAuras: z.array(supportAuraModifierSchema).optional(),
  periodicAbilities: z.array(z.record(z.string(), z.unknown())).optional(),
  triggerEffects: z.array(z.record(z.string(), z.unknown())).optional(),
  fieldEffect: z.array(z.record(z.string(), z.unknown())).optional(),
  controlBeam: z.record(z.string(), z.unknown()).optional(),
  rankScaling: z.record(z.string(), z.unknown()).optional(),
}).passthrough()

export type PreparedStats = z.infer<typeof preparedStatsSchema>
